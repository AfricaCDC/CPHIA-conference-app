#!/usr/bin/env bash
# Build a production Android debug/release APK with the live MOBILE_APP_API_KEY baked in.
# Usage:
#   ./scripts/build-android-production.sh           # debug APK
#   ./scripts/build-android-production.sh release   # release APK (needs signing config)
#
# Key resolution order:
#   1) VITE_MOBILE_APP_API_KEY or MOBILE_APP_API_KEY already in the environment
#   2) ssh cphia → /var/lib/CPHIA/CPHIA/.env  (production)
#   3) repo-root .env MOBILE_APP_API_KEY (local fallback; warn if used)

set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
REPO="$(cd "$ROOT/../" && pwd)"
VARIANT="${1:-debug}"
API_BASE="${VITE_API_BASE_URL:-https://admincphia.africacdc.org/api/mobile/v1}"
OUT_NAME="${ANDROID_APK_NAME:-CPHIA-2026-${VARIANT}.apk}"
OUT_PATH="${ANDROID_APK_OUT:-$REPO/$OUT_NAME}"

read_key_from_env_file() {
  local file="$1"
  local name="$2"
  [[ -f "$file" ]] || return 1
  local line
  line="$(grep -E "^${name}=" "$file" | tail -n1 || true)"
  [[ -n "$line" ]] || return 1
  printf '%s' "${line#*=}" | tr -d '"' | tr -d "'" | tr -d '\r'
}

resolve_api_key() {
  if [[ -n "${VITE_MOBILE_APP_API_KEY:-}" ]]; then
    printf '%s' "$VITE_MOBILE_APP_API_KEY"
    return 0
  fi
  if [[ -n "${MOBILE_APP_API_KEY:-}" ]]; then
    printf '%s' "$MOBILE_APP_API_KEY"
    return 0
  fi

  # Prefer the live production key so APKs talk to admincphia successfully.
  if command -v ssh >/dev/null 2>&1; then
    local remote
    remote="$(ssh -o BatchMode=yes -o ConnectTimeout=8 cphia \
      'grep -E "^MOBILE_APP_API_KEY=" /var/lib/CPHIA/CPHIA/.env | tail -n1' 2>/dev/null || true)"
    if [[ -n "$remote" ]]; then
      printf '%s' "${remote#*=}" | tr -d '"' | tr -d "'" | tr -d '\r'
      echo "Using MOBILE_APP_API_KEY from production (ssh cphia)." >&2
      return 0
    fi
  fi

  local local_key
  local_key="$(read_key_from_env_file "$REPO/.env" MOBILE_APP_API_KEY || true)"
  if [[ -n "$local_key" ]]; then
    echo "WARNING: Using MOBILE_APP_API_KEY from local repo .env (may not match production)." >&2
    printf '%s' "$local_key"
    return 0
  fi

  local_key="$(read_key_from_env_file "$ROOT/.env" VITE_MOBILE_APP_API_KEY || true)"
  if [[ -n "$local_key" ]]; then
    echo "WARNING: Using VITE_MOBILE_APP_API_KEY from cphia_pwa/.env." >&2
    printf '%s' "$local_key"
    return 0
  fi

  echo "ERROR: No mobile app API key found. Set MOBILE_APP_API_KEY or VITE_MOBILE_APP_API_KEY." >&2
  return 1
}

KEY="$(resolve_api_key)"
if [[ -z "$KEY" || ${#KEY} -lt 16 ]]; then
  echo "ERROR: Resolved API key looks empty or too short." >&2
  exit 1
fi

# Persist for local Capacitor rebuilds (gitignored). Do not commit this file.
umask 077
cat > "$ROOT/.env.native.production" <<EOF
# Generated by scripts/build-android-production.sh — do not commit.
CAPACITOR_BUILD=1
VITE_API_BASE_URL=${API_BASE}
VITE_MOBILE_APP_API_KEY=${KEY}
EOF

# Keep cphia_pwa/.env in sync so accidental vite builds also send the header.
if [[ -f "$ROOT/.env" ]]; then
  if grep -q '^VITE_MOBILE_APP_API_KEY=' "$ROOT/.env"; then
    # portable in-place replace
    tmp="$(mktemp)"
    awk -v key="$KEY" '
      BEGIN { done=0 }
      /^VITE_MOBILE_APP_API_KEY=/ { print "VITE_MOBILE_APP_API_KEY=" key; done=1; next }
      { print }
      END { if (!done) print "VITE_MOBILE_APP_API_KEY=" key }
    ' "$ROOT/.env" > "$tmp" && mv "$tmp" "$ROOT/.env"
  else
    printf '\nVITE_MOBILE_APP_API_KEY=%s\n' "$KEY" >> "$ROOT/.env"
  fi
else
  cp "$ROOT/.env.example" "$ROOT/.env"
  printf '\nVITE_MOBILE_APP_API_KEY=%s\n' "$KEY" >> "$ROOT/.env"
fi

export JAVA_HOME="${JAVA_HOME:-/Users/andre/Library/Java/jdk21/Contents/Home}"
if [[ ! -x "$JAVA_HOME/bin/java" ]]; then
  JAVA_HOME="/Applications/Android Studio.app/Contents/jbr/Contents/Home"
fi
export ANDROID_HOME="${ANDROID_HOME:-$HOME/Library/Android/sdk}"
export PATH="$JAVA_HOME/bin:$ANDROID_HOME/platform-tools:$PATH"

printf 'sdk.dir=%s\n' "$ANDROID_HOME" > "$ROOT/android/local.properties"

echo "Building native web bundle (API ${API_BASE}, key len ${#KEY}, prefix ${KEY:0:8}…)"
cd "$ROOT"
CAPACITOR_BUILD=1 \
VITE_API_BASE_URL="$API_BASE" \
VITE_MOBILE_APP_API_KEY="$KEY" \
npx vite build

npx cap sync android

cd "$ROOT/android"
if [[ "$VARIANT" == "release" ]]; then
  ./gradlew assembleRelease --no-daemon
  APK_SRC="$ROOT/android/app/build/outputs/apk/release/app-release.apk"
  if [[ ! -f "$APK_SRC" ]]; then
    APK_SRC="$ROOT/android/app/build/outputs/apk/release/app-release-unsigned.apk"
  fi
else
  ./gradlew assembleDebug --no-daemon
  APK_SRC="$ROOT/android/app/build/outputs/apk/debug/app-debug.apk"
fi

cp "$APK_SRC" "$OUT_PATH"
echo "APK ready: $OUT_PATH ($(du -h "$OUT_PATH" | awk '{print $1}'))"
echo "Install: adb install -r \"$OUT_PATH\""
